import { MODELS } from './catalog.js';

// Demo provider used until trained Raken models are deployed. Replace
// `generate` with a call to the real inference endpoint; the return shape
// ({ text, file? }) is what the server and web app expect.
export async function generate({ tool, modelId, prompt, ultra }) {
  const model = MODELS[modelId];
  const speed = ultra ? 'Ultra (priority cluster)' : 'standard queue';

  if (tool === 'work') {
    const name = `${slug(prompt) || 'raken-output'}.md`;
    return {
      text: `${model.name} agents drafted ${name} for you (${speed}).`,
      file: { name, content: `# ${prompt}\n\nDraft generated by ${model.name} (demo provider).\n` },
    };
  }

  const byKind = {
    image: `[demo] ${model.name} would render an image of: "${prompt}"`,
    video: `[demo] ${model.name} would create a short movie of: "${prompt}"`,
    mesh: `[demo] ${model.name} would generate an 8K 3D model of: "${prompt}"`,
    text: `[demo] ${model.name} received: "${prompt}". Connect a trained model in src/provider.js to get real answers.`,
  };
  return { text: `${byKind[model.kind]} — ${speed}.` };
}

function slug(text) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40);
}
